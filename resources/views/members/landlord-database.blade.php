<h1 class="mb-4">Landlord Database</h1>

<p>The Renters' Rights Act 2025 introduces a mandatory Private Rented Sector Database. All landlords must register.</p>

<hr>

<h3 class="mb-3">Planned Features</h3>

<ul>
    <li>Compulsory registration of all landlords</li>
    <li>Property-level records for every rental</li>
    <li>Compliance status visible to tenants</li>
    <li>Local authority enforcement tools</li>
    <li>Public search functionality</li>
</ul>

<hr>

<h3 class="mb-3">Implementation Timeline</h3>

<ul>
    <li><strong>Royal Assent:</strong> 27 October 2025</li>
    <li><strong>Phase 1 (May 2026):</strong> Main provisions</li>
    <li><strong>Phase 2 (Late 2026):</strong> Database rollout begins</li>
    <li><strong>Full launch (2028):</strong> Nationwide coverage expected</li>
</ul>

<p>Rollout is area-by-area. Public access follows registration in each region. Government IT timelines may slip.</p>

<hr>

<h3 class="mb-3">Why It's Needed</h3>

<ul>
    <li>No central record of who lets properties</li>
    <li>Rogue landlords operate undetected</li>
    <li>Tenants can't verify landlord legitimacy</li>
    <li>Local authorities lack PRS visibility</li>
    <li>Compliance can't be monitored</li>
    <li>Enforcement is reactive, not preventive</li>
</ul>

<hr>

<h3 class="mb-3">Who Benefits</h3>

<p><strong>Landlords</strong> — Single platform for guidance and demonstrating compliance.</p>

<p><strong>Tenants</strong> — Check landlord registration and verify property is legally let.</p>

<p><strong>Councils</strong> — Identify problem properties and target enforcement.</p>

<hr>

<h3 class="mb-3">Non-Compliance Penalties</h3>

<ul>
    <li><strong>£7,000</strong> — Initial breach</li>
    <li><strong>£40,000</strong> — Repeated breaches</li>
    <li><strong>No evictions</strong> — Until registered</li>
</ul>
@endsection
