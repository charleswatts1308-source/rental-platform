<p>41% of private renters live in flats. 34% live in terraced houses, typically older Victorian or Edwardian stock. 75% of the entire sector lives in one of these two property types.</p>

<hr>

<h3 class="mb-3">What this means in practice</h3>

<p>The private rented sector is not modern purpose-built housing. It is predominantly older stock — houses and conversions that were built for owner-occupation, not professional letting. Many of these properties have ageing heating systems, poor insulation, and structural characteristics that make damp and cold a persistent problem rather than an occasional one.</p>

<p>A significant portion of PRS housing entered the rental market not because it was purpose-built for that role, but because owners moved on, inherited property, or couldn't sell. The tenant inherits whatever condition the property was in.</p>

<hr>

<h3 class="mb-3">The age of the stock</h3>

<p>Older properties require more maintenance. That is not an opinion — it is a function of building physics. A Victorian terraced house with single-glazed windows, solid walls and an ageing boiler will generate more repair requests than a new-build apartment. Yet it is exactly this kind of property that dominates the PRS.</p>

<p>The combination of older stock, under-invested maintenance, and tenants who have historically been reluctant to complain for fear of eviction has created a sector with a significant and largely undocumented repair backlog.</p>

<p>That backlog now has somewhere to go.</p>

