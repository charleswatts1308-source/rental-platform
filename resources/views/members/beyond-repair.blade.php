<h1 class="mb-4">Beyond Repair — The Equity Conversation</h1>

<p>The repair notice process exists to get things fixed. But for some tenants, in some situations, it may open a door to something more significant.</p>

<hr>

<h3 class="mb-3">When a landlord can't afford to repair</h3>

<p>Not every landlord is a wealthy investor. Many are over-leveraged, operating on thin margins, with properties that have deferred maintenance they cannot fund. When a formal repair notice arrives — documented, timestamped, legally referenced — a landlord in that position faces a calculation.</p>

<p>They can fix it, which they may not be able to afford. They can ignore it, which now carries real legal risk. Or they can negotiate.</p>

<p>A tenant with a documented repair trail, security of tenure under the new legislation, and no fear of eviction is in a stronger negotiating position than any tenant has been in decades. What that negotiation looks like is up to both parties — but equity is a legitimate option on the table.</p>

<hr>

<h3 class="mb-3">What an equity arrangement could look like</h3>

<p>There is no established template for this — it has rarely happened in residential rental because tenants have never had the leverage to propose it. But the principle is straightforward: instead of, or alongside, carrying out repairs, the landlord transfers a share of the property's equity to the tenant.</p>

<p>The tenant gets a stake in the asset their rent has been financing. The landlord resolves an obligation they couldn't otherwise meet. Both parties have a new shared interest in the property.</p>

<p>This would require proper legal documentation — a solicitor would need to be involved. But the commercial logic is sound, and there is nothing in law that prevents it.</p>

<hr>

<h3 class="mb-3">The longer game</h3>

<p>Individual equity arrangements, negotiated quietly between one tenant and one landlord, are one thing. The more significant possibility is what happens when organised groups of tenants — sharing a landlord, coordinating through a platform — begin to negotiate collectively.</p>

<p>At that point the conversation shifts from "fix my boiler" to "restructure our relationship." That is not a threat. It is simply what leverage, properly applied, makes possible.</p>

<p>Employee ownership was once a fringe idea. It is now mainstream. The private rental contract has not changed in substance for a generation. It will.</p>

<hr>

<h3 class="mb-3">A note on the repair notice service</h3>

<p>The repair notice service is designed to get repairs done. That remains its primary purpose. But a formal, documented repair trail is also the foundation of any subsequent negotiation. Every notice sent, every deadline missed, every inadequate response recorded — that is a paper trail that has value beyond the immediate dispute.</p>

<p>Start with the repair. See where it leads.</p>

