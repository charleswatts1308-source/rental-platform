<h3 class="mb-3">Where the money goes</h3>

<p>For landlords who spend it locally, rental income recirculates — in local shops, local services, the local economy. But a meaningful portion of the PRS is owned by non-resident landlords whose income, once received, leaves the communities that generated it entirely.</p>

<p>The government operates a dedicated scheme — the Non-Resident Landlord Scheme — specifically to collect tax on rental income before it reaches overseas owners. The mere existence of that scheme tells you something about the scale of the flow.</p>

<hr>

<h3 class="mb-3">The human cost</h3>

<p>£77 billion a year sounds abstract. It becomes less so when you consider that the average private renter in full-time work spends 26% of their income on rent. In London that rises to 46%. For renters in the lowest income brackets, more than half of everything they earn goes on housing.</p>

<p>This is not money spent on a mortgage that builds equity. It is money that leaves the tenant's hands permanently, every month, with nothing accumulated in return.</p>

<hr>

<h3 class="mb-3">The scrutiny gap</h3>

<p>A sector moving £77 billion a year would normally attract intense regulatory scrutiny. Compare it to financial services, utilities, or even supermarkets — all heavily regulated, all subject to public accountability mechanisms, all expected to justify their pricing.</p>

<p>The private rental sector has operated largely outside that framework. No pricing regulator. No mandatory standards enforcement with teeth. No organised voice on the tenant side.</p>

<p>That is what this platform exists to change.</p>

