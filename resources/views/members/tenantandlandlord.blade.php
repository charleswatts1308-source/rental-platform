<h1 class="mb-4">Tenant and Landlord</h1>

<p>Renting isn't new. The landlord-tenant relationship has its roots in feudalism - a system of land use and ownership that emerged in Europe between the tenth and thirteenth centuries. Lords held land; tenants worked it in exchange for protection. The power imbalance was absolute.</p>

<hr>

<h3 class="mb-3">The Dynamic Persists</h3>

<p>A thousand years on, the dynamic persists. Landlords own; tenants occupy. One has capital, the other needs shelter. The tension is baked in.</p>

<p>In England, Section 21 of the Housing Act 1988 handed landlords a trump card: evict with two months' notice, no reason needed. Even better for the landlord.</p>

<hr>

<h3 class="mb-3">But ... No Longer</h3>

<p>From 1st May 2026, Section 21 is gone. The Renters' Rights Act requires landlords to justify every eviction.
   <br>Rent arrears, antisocial behaviour, selling up - are all still valid reasons.
   <br>But "because I said so" is no longer enough.</p>

<p class="lead">At long, long last, the law has changed back, in the tenant's favour.</p>
