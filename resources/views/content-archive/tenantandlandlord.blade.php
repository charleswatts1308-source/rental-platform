<h1 class="mb-4">Tenant and Landlord</h1>

<p>Renting isn't new - its been around for a very long time.
    The landlord-tenant relationship has its roots in feudalism -
    a system of land use and ownership that emerged in Europe between the tenth and thirteenth centuries.
    Lords held land; tenants worked it in exchange for protection. The power imbalance was absolute.</p>

<hr>

<h3 class="mb-3">Landlord Rights Increased</h3>

<p>A thousand years on, the dynamic persists. Landlords own; tenants occupy. One has capital, the other needs shelter. The tension is baked in.</p>

<p>In England, Section 21 of the Housing Act 1988 handed landlords a trump card: evict with two months' notice, no reason needed.
    This made it very easy for landlords to continously increase rents.
    The threat of retaliatory eviction was a very powerful weapon. Now its gone.

</p>

<hr>

<h3 class="mb-3">And now ... Tenants Rights Increased</h3>

<p>From 1st May 2026, Section 21 is gone. The Renters' Rights Act requires landlords to justify every eviction in a court.
   Valid reasons are limited to: Rent arrears, antisocial behaviour, selling up.</p>

<p>The law has changed to favour the tenant.</p>
