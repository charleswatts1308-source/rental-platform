<h1 class="mb-4">What If Every Renter Stopped Paying?</h1>

<p>It's a thought experiment, nothing more. If the UK's 4.7 million renting households withheld rent simultaneously, the legal system would collapse overnight. Courts can't process millions of possession orders. Mass CCJs become worthless paper. There's no replacement tenant pool — who moves in?</p>

<p>Of course it would never happen. Emergency legislation would follow within weeks, and rightly so. The state could not allow such chaos.</p>

<hr>

<p>But here's the interesting part: even as pure fantasy, who exactly has the public's sympathy? Landlords — many holding multiple properties, leveraged on the back of a generation priced out of ownership — or the tenants writing the cheques?</p>

<p>And consider where the money goes. Withheld rent doesn't vanish.
    It stays in the hands of working people who spend it in their local economy.
    The landlord's mortgage payment pauses.
    The tenant's grocery shop doesn't.
    How many landlord pensions are quietly being funded by renters who can't afford one themselves?</p>

<hr>

<p>Section 21 was introduced in 1989, before the internet existed. Tenants couldn't find each other. That was the world the rental contract was designed for. It isn't the world we live in now.</p>

<p>A tenancy agreement is just a private contract between two private individuals. Its power comes entirely from the legislation behind it — and that legislation just shifted fundamentally in the tenant's favour. That's a negotiation, not a sentence.</p>

<hr>

<p>The point isn't to advocate for anything. It's to understand where power actually sits. Organised renters — even just visibly organised — represent a risk that rational property investors have to price in.</p>

<p>That's what this platform is building. Visible organisation. Quiet leverage.</p>

<p>Leverage opens negotiations that don't currently exist. You pay, they own, nothing changes — but only because tenants have never had the power to demand otherwise. An organised base could change that: contracts with an equity stake, a share in the appreciation your rent has been financing for years.</p>

